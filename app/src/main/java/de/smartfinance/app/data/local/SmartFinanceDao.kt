package de.smartfinance.app.data.local

import androidx.room.Dao
import androidx.room.Delete
import androidx.room.Insert
import androidx.room.OnConflictStrategy
import androidx.room.Query
import androidx.room.Update
import kotlinx.coroutines.flow.Flow

@Dao
interface SmartFinanceDao {

    // --- KATEGORIEN & VERTRÄGE ---
    @Query("SELECT * FROM category_tabs ORDER BY sortOrder ASC, id ASC")
    fun observeCategoryTabs(): Flow<List<CategoryTabEntity>>

    @Query("SELECT * FROM category_tabs ORDER BY sortOrder ASC, id ASC")
    suspend fun getAllCategoryTabsOnce(): List<CategoryTabEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertCategoryTab(tab: CategoryTabEntity): Long

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertCategoryTabs(tabs: List<CategoryTabEntity>): List<Long>

    @Update
    suspend fun updateCategoryTab(tab: CategoryTabEntity)

    @Delete
    suspend fun deleteCategoryTab(tab: CategoryTabEntity)

    @Query("DELETE FROM category_tabs")
    suspend fun deleteAllCategoryTabs()

    // --- TRANSAKTIONEN / BUCHUNGEN ---
    @Query("SELECT * FROM transactions ORDER BY dateEpochDay DESC, id DESC")
    fun observeAllTransactions(): Flow<List<TransactionEntity>>

    @Query("SELECT * FROM transactions ORDER BY dateEpochDay DESC, id DESC")
    suspend fun getAllTransactionsOnce(): List<TransactionEntity>

    @Query("SELECT * FROM transactions WHERE autoGeneratedKey = :autoKey LIMIT 1")
    suspend fun findTransactionByAutoKey(autoKey: String): TransactionEntity?

    @Insert(onConflict = OnConflictStrategy.IGNORE)
    suspend fun insertTransaction(transaction: TransactionEntity): Long

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertTransactionsReplace(transactions: List<TransactionEntity>)

    @Update
    suspend fun updateTransaction(transaction: TransactionEntity)

    @Delete
    suspend fun deleteTransaction(transaction: TransactionEntity)

    @Query("DELETE FROM transactions")
    suspend fun deleteAllTransactions()

    // --- SPARZIELE ---
    @Query("SELECT * FROM savings_goals ORDER BY id ASC")
    fun observeSavingsGoals(): Flow<List<SavingsGoalEntity>>

    @Query("SELECT * FROM savings_goals ORDER BY id ASC")
    suspend fun getAllSavingsGoalsOnce(): List<SavingsGoalEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertSavingsGoal(goal: SavingsGoalEntity): Long

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertSavingsGoals(goals: List<SavingsGoalEntity>)

    @Update
    suspend fun updateSavingsGoal(goal: SavingsGoalEntity)

    @Query("DELETE FROM savings_goals")
    suspend fun deleteAllSavingsGoals()

    // --- 1-TAP SCHNELLVORLAGEN ---
    @Query("SELECT * FROM quick_templates ORDER BY id ASC")
    fun observeQuickTemplates(): Flow<List<QuickTemplateEntity>>

    @Query("SELECT * FROM quick_templates ORDER BY id ASC")
    suspend fun getAllQuickTemplatesOnce(): List<QuickTemplateEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertQuickTemplate(template: QuickTemplateEntity): Long

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertQuickTemplates(templates: List<QuickTemplateEntity>)

    @Delete
    suspend fun deleteQuickTemplate(template: QuickTemplateEntity)

    @Query("DELETE FROM quick_templates")
    suspend fun deleteAllQuickTemplates()
}
