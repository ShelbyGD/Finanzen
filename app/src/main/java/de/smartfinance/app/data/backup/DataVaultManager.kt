                    ${today.minusDays(4).format(fmt)};Telekom Deutschland GmbH;Mobilfunk Rechnung Handyvertrag;-29,99;EUR
                    ${today.minusDays(3).format(fmt)};Allianz Versicherungs-AG;Hausrat & Privathaftpflicht;-42,50;EUR
