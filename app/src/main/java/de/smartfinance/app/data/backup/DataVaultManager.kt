data class VaultOperationResult(
    val success: Boolean,
    val message: String,
    val importedCount: Int = 0
)

/**
 * Daten-Tresor für 1-Tap JSON-Komplett-Backup, JSON-Restore und Bank-CSV-Kontoauszug-Import.
 */
class DataVaultManager(
    private val dao: SmartFinanceDao,
    private val preferences: AppPreferences
) {

    suspend fun createBackupJsonString(): String {
        val categories = dao.getAllCategoryTabsOnce()
        val transactions = dao.getAllTransactionsOnce()
        val goals = dao.getAllSavingsGoalsOnce()
        val templates = dao.getAllQuickTemplatesOnce()
        val settings = preferences.settingsState.value

        val root = JSONObject()
        root.put("schemaVersion", 1)
        root.put("appVersion", BuildConfig.VERSION_NAME)
        root.put("buildNumber", BuildConfig.BUILD_NUMBER)
        root.put("exportedAt", LocalDateTime.now().format(DateTimeFormatter.ISO_LOCAL_DATE_TIME))

        val settingsObj = JSONObject().apply {
            put("billingStartDay", settings.billingStartDay)
            put("hourlyWage", settings.hourlyWage)
            put("averageMonthsWindow", settings.averageMonthsWindow)
        }
        root.put("settings", settingsObj)

        val catArray = JSONArray()
        categories.forEach { cat ->
            catArray.put(
                JSONObject().apply {
                    put("id", cat.id)
                    put("name", cat.name)
                    put("iconKey", cat.iconKey)
                    put("colorHex", cat.colorHex)
                    put("categoryType", cat.categoryType)
                    if (cat.monthlyBudgetLimit != null) put("monthlyBudgetLimit", cat.monthlyBudgetLimit)
                    if (cat.dueDayOfMonth != null) put("dueDayOfMonth", cat.dueDayOfMonth)
                    if (cat.defaultAmount != null) put("defaultAmount", cat.defaultAmount)
                    put("billingInterval", cat.billingInterval)
                    put("smoothOver12Months", cat.smoothOver12Months)
                    if (cat.contractEndDateEpochDay != null) put("contractEndDateEpochDay", cat.contractEndDateEpochDay)
                    put("isSystemDefault", cat.isSystemDefault)
                    put("sortOrder", cat.sortOrder)
                }
            )
        }
        root.put("categories", catArray)

        val txArray = JSONArray()
        transactions.forEach { tx ->
            txArray.put(
                JSONObject().apply {
                    put("id", tx.id)
                    put("title", tx.title)
                    put("amount", tx.amount)
                    put("transactionType", tx.transactionType)
                    put("categoryId", tx.categoryId)
                    put("categoryName", tx.categoryName)
                    put("dateEpochDay", tx.dateEpochDay)
                    put("dueDayOfMonth", tx.dueDayOfMonth)
                    put("isFixedRecurring", tx.isFixedRecurring)
                    put("billingInterval", tx.billingInterval)
                    put("smoothOver12Months", tx.smoothOver12Months)
                    put("note", tx.note)
                    if (tx.autoGeneratedKey != null) put("autoGeneratedKey", tx.autoGeneratedKey)
                }
            )
        }
        root.put("transactions", txArray)

        val goalArray = JSONArray()
        goals.forEach { g ->
            goalArray.put(
                JSONObject().apply {
                    put("id", g.id)
                    put("title", g.title)
                    put("targetAmount", g.targetAmount)
                    put("initialSavedAmount", g.initialSavedAmount)
                    put("monthlyContributionGoal", g.monthlyContributionGoal)
                    put("dueDayOfMonth", g.dueDayOfMonth)
                }
            )
        }
        root.put("savingsGoals", goalArray)

        val tplArray = JSONArray()
        templates.forEach { t ->
            tplArray.put(
                JSONObject().apply {
                    put("id", t.id)
                    put("label", t.label)
                    put("emoji", t.emoji)
                    put("amount", t.amount)
                    put("categoryId", t.categoryId)
                    put("categoryName", t.categoryName)
                    put("transactionType", t.transactionType)
                }
            )
        }
        root.put("quickTemplates", tplArray)

        return root.toString(2)
    }

    suspend fun restoreFromBackupJsonString(jsonContent: String): VaultOperationResult {
        return try {
            val root = JSONObject(jsonContent)

            val settingsObj = root.optJSONObject("settings")
            if (settingsObj != null) {
                preferences.importFromMap(
                    billingStartDay = settingsObj.optInt("billingStartDay", 1),
                    hourlyWage = settingsObj.optDouble("hourlyWage", 15.75),
                    averageMonthsWindow = settingsObj.optInt("averageMonthsWindow", 3)
                )
            }

            val catArray = root.optJSONArray("categories") ?: JSONArray()
            val parsedCategories = mutableListOf<CategoryTabEntity>()
            for (i in 0 until catArray.length()) {
                val obj = catArray.getJSONObject(i)
                parsedCategories.add(
                    CategoryTabEntity(
                        id = obj.optLong("id", 0L),
                        name = obj.getString("name"),
                        iconKey = obj.optString("iconKey", "cart"),
                        colorHex = obj.optLong("colorHex", 0xFF38BDF8),
                        categoryType = obj.optString("categoryType", CategoryType.VARIABLE_EXPENSE),
                        monthlyBudgetLimit = if (obj.has("monthlyBudgetLimit")) obj.getDouble("monthlyBudgetLimit") else null,
                        dueDayOfMonth = if (obj.has("dueDayOfMonth")) obj.getInt("dueDayOfMonth") else null,
                        defaultAmount = if (obj.has("defaultAmount")) obj.getDouble("defaultAmount") else null,
                        billingInterval = obj.optString("billingInterval", BillingInterval.ONE_TIME),
                        smoothOver12Months = obj.optBoolean("smoothOver12Months", false),
                        contractEndDateEpochDay = if (obj.has("contractEndDateEpochDay")) obj.getLong("contractEndDateEpochDay") else null,
                        isSystemDefault = obj.optBoolean("isSystemDefault", false),
                        sortOrder = obj.optInt("sortOrder", i)
                    )
                )
            }

            val txArray = root.optJSONArray("transactions") ?: JSONArray()
            val parsedTransactions = mutableListOf<TransactionEntity>()
            for (i in 0 until txArray.length()) {
                val obj = txArray.getJSONObject(i)
                parsedTransactions.add(
                    TransactionEntity(
                        id = obj.optLong("id", 0L),
                        title = obj.getString("title"),
                        amount = obj.getDouble("amount"),
                        transactionType = obj.optString("transactionType", TransactionType.EXPENSE),
                        categoryId = obj.optLong("categoryId", 1L),
                        categoryName = obj.optString("categoryName", "Lebensmittel"),
                        dateEpochDay = obj.getLong("dateEpochDay"),
                        dueDayOfMonth = obj.optInt("dueDayOfMonth", 1),
                        isFixedRecurring = obj.optBoolean("isFixedRecurring", false),
                        billingInterval = obj.optString("billingInterval", BillingInterval.ONE_TIME),
                        smoothOver12Months = obj.optBoolean("smoothOver12Months", false),
                        note = obj.optString("note", ""),
                        autoGeneratedKey = if (obj.has("autoGeneratedKey") && !obj.isNull("autoGeneratedKey")) {
                            obj.getString("autoGeneratedKey")
                        } else {
                            null
                        }
                    )
                )
            }

            val goalArray = root.optJSONArray("savingsGoals") ?: JSONArray()
            val parsedGoals = mutableListOf<SavingsGoalEntity>()
            for (i in 0 until goalArray.length()) {
                val obj = goalArray.getJSONObject(i)
                parsedGoals.add(
                    SavingsGoalEntity(
                        id = obj.optLong("id", 0L),
                        title = obj.getString("title"),
                        targetAmount = obj.getDouble("targetAmount"),
                        initialSavedAmount = obj.optDouble("initialSavedAmount", 0.0),
                        monthlyContributionGoal = obj.optDouble("monthlyContributionGoal", 100.0),
                        dueDayOfMonth = obj.optInt("dueDayOfMonth", 1)
                    )
                )
            }

            val tplArray = root.optJSONArray("quickTemplates") ?: JSONArray()
            val parsedTemplates = mutableListOf<QuickTemplateEntity>()
            for (i in 0 until tplArray.length()) {
                val obj = tplArray.getJSONObject(i)
                parsedTemplates.add(
                    QuickTemplateEntity(
                        id = obj.optLong("id", 0L),
                        label = obj.getString("label"),
                        emoji = obj.optString("emoji", "cart"),
                        amount = obj.getDouble("amount"),
                        categoryId = obj.optLong("categoryId", 1L),
                        categoryName = obj.optString("categoryName", "Lebensmittel"),
                        transactionType = obj.optString("transactionType", TransactionType.EXPENSE)
                    )
                )
            }

            dao.deleteAllTransactions()
            dao.deleteAllCategoryTabs()
            dao.deleteAllSavingsGoals()
            dao.deleteAllQuickTemplates()

            if (parsedCategories.isNotEmpty()) dao.insertCategoryTabs(parsedCategories)
            if (parsedTransactions.isNotEmpty()) dao.insertTransactionsReplace(parsedTransactions)
            if (parsedGoals.isNotEmpty()) dao.insertSavingsGoals(parsedGoals)
            if (parsedTemplates.isNotEmpty()) dao.insertQuickTemplates(parsedTemplates)

            VaultOperationResult(
                success = true,
                message = "JSON-Backup erfolgreich wiederhergestellt (${parsedTransactions.size} Buchungen, ${parsedCategories.size} Kategorien).",
                importedCount = parsedTransactions.size
            )
        } catch (e: Exception) {
            VaultOperationResult(
                success = false,
                message = "Fehler beim JSON-Restore: ${e.localizedMessage ?: "Ungültiges Dateiformat"}"
            )
        }
    }

    /**
     * Importiert deutsche Bank-CSV-Dateien (z. B. Sparkasse, ING, DKB, Volksbank, N26).
     * Erkennt automatisch Semikolon/Komma-Trennung, deutsche Zahlenformate (-1.234,56) und Datumswerte.
     */
    suspend fun importBankCsvContent(csvContent: String): VaultOperationResult {
        return try {
            val categories = dao.getAllCategoryTabsOnce()
            val defaultExpenseCat = categories.firstOrNull { it.name.contains("Lebensmittel", ignoreCase = true) }
                ?: categories.firstOrNull()
            val incomeCat = categories.firstOrNull { it.categoryType == CategoryType.INCOME } ?: defaultExpenseCat

            val lines = csvContent.lines().map { it.trim() }.filter { it.isNotEmpty() }
            if (lines.isEmpty()) {
                return VaultOperationResult(false, "Die CSV-Datei ist leer.")
            }

            var importedCount = 0
            val amountRegex = Regex("""[-+]?\s*(?:\d{1,3}(?:\.\d{3})+|\d+),\d{2}|[-+]?\s*\d+\.\d{2}""")
            val germanDateRegex = Regex("""(\d{2})\.(\d{2})\.(\d{2,4})""")
            val isoDateRegex = Regex("""(\d{4})-(\d{2})-(\d{2})""")

            for (line in lines) {
                val lowerLine = line.lowercase()
                if (lowerLine.startsWith("buchungstag") ||
                    lowerLine.startsWith("datum") ||
                    lowerLine.startsWith("\"buchungstag") ||
                    lowerLine.startsWith("valutadatum")
                ) {
                    continue
                }

                val delimiter = if (line.count { it == ';' } >= 2) ';' else ','
                val columns = line.split(delimiter).map { it.trim().trim('"') }
                if (columns.size < 2) continue

                // 1. Datum suchen
                var parsedDate: LocalDate? = null
                for (col in columns) {
                    val deMatch = germanDateRegex.find(col)
                    if (deMatch != null) {
                        val day = deMatch.groupValues[1].toIntOrNull() ?: 1
                        val month = deMatch.groupValues[2].toIntOrNull() ?: 1
                        var year = deMatch.groupValues[3].toIntOrNull() ?: LocalDate.now().year
                        if (year < 100) year += 2000
                        parsedDate = runCatching { LocalDate.of(year, month, day) }.getOrNull()
                        if (parsedDate != null) break
                    }
                    val isoMatch = isoDateRegex.find(col)
                    if (isoMatch != null) {
                        val year = isoMatch.groupValues[1].toIntOrNull() ?: LocalDate.now().year
                        val month = isoMatch.groupValues[2].toIntOrNull() ?: 1
                        val day = isoMatch.groupValues[3].toIntOrNull() ?: 1
                        parsedDate = runCatching { LocalDate.of(year, month, day) }.getOrNull()
                        if (parsedDate != null) break
                    }
                }
                val date = parsedDate ?: LocalDate.now()

                // 2. Betrag suchen (meist in den hinteren Spalten)
                var rawAmountSigned: Double? = null
                for (col in columns.reversed()) {
                    val match = amountRegex.find(col)
                    if (match != null && !germanDateRegex.matches(col)) {
                        val token = match.value.replace(" ", "")
                        val normalized = if (token.contains(',')) {
                            token.replace(".", "").replace(",", ".")
                        } else {
                            token
                        }
                        val value = normalized.toDoubleOrNull()
                        if (value != null && abs(value) > 0.0) {
                            rawAmountSigned = value
                            break
                        }
                    }
                }
                val signedAmount = rawAmountSigned ?: continue

                // 3. Verwendungszweck / Empfänger bestimmen
                val textColumns = columns.filter { col ->
                    !germanDateRegex.matches(col) &&
                        !isoDateRegex.matches(col) &&
                        amountRegex.find(col)?.value != col &&
                        col.length > 2
                }
                val description = textColumns.joinToString(" – ").take(90).ifBlank { "Bank-CSV Buchung" }

                // 4. Intelligente Kategorien-Zuordnung
                val isIncome = signedAmount > 0.0 && (
                    description.contains("Gehalt", ignoreCase = true) ||
                        description.contains("Lohn", ignoreCase = true) ||
                        description.contains("Gutschrift", ignoreCase = true) ||
                        description.contains("Überweisung Eingang", ignoreCase = true) ||
                        signedAmount >= 400.0
                    )

                val matchedCategory = if (isIncome) {
                    incomeCat
                } else {
                    matchCategoryByDescription(description, categories) ?: defaultExpenseCat
                }

                val txType = when {
                    isIncome -> TransactionType.INCOME
                    matchedCategory?.categoryType == CategoryType.SAVINGS -> TransactionType.SAVINGS
                    else -> TransactionType.EXPENSE
                }

                dao.insertTransaction(
                    TransactionEntity(
                        title = description,
                        amount = abs(signedAmount),
                        transactionType = txType,
                        categoryId = matchedCategory?.id ?: 1L,
                        categoryName = matchedCategory?.name ?: "Lebensmittel",
                        dateEpochDay = date.toEpochDay(),
                        dueDayOfMonth = date.dayOfMonth,
                        isFixedRecurring = matchedCategory?.categoryType == CategoryType.FIXED_EXPENSE,
                        billingInterval = matchedCategory?.billingInterval ?: BillingInterval.ONE_TIME,
                        smoothOver12Months = matchedCategory?.smoothOver12Months ?: false,
                        note = "Importiert via Bank-CSV"
                    )
                )
                importedCount++
            }

            if (importedCount > 0) {
                VaultOperationResult(
                    success = true,
                    message = "$importedCount Bank-Umsätze erfolgreich aus CSV importiert und kategorisiert!",
                    importedCount = importedCount
                )
            } else {
                VaultOperationResult(
                    success = false,
                    message = "Keine gültigen Buchungszeilen in der CSV-Datei erkannt."
                )
            }
        } catch (e: Exception) {
            VaultOperationResult(
                success = false,
                message = "CSV-Import-Fehler: ${e.localizedMessage ?: "Unbekannter Fehler"}"
            )
        }
    }

    private fun matchCategoryByDescription(
        text: String,
        categories: List<CategoryTabEntity>
    ): CategoryTabEntity? {
        val lower = text.lowercase()
        val targetName = when {
            lower.contains("telekom") || lower.contains("vodafone") || lower.contains("o2") || lower.contains("mobilfunk") || lower.contains("handy") -> "Handyvertrag"
            lower.contains("kfz") || lower.contains("huk") || lower.contains("autoversicherung") || lower.contains("adac") -> "Kfz-Versicherung"
            lower.contains("allianz") || lower.contains("versicherung") || lower.contains("haftpflicht") || lower.contains("hausrat") -> "Versicherung"
            lower.contains("rewe") || lower.contains("edeka") || lower.contains("aldi") || lower.contains("lidl") || lower.contains("kaufland") || lower.contains("dm ") || lower.contains("rossmann") || lower.contains("bäcker") -> "Lebensmittel"
            lower.contains("miete") || lower.contains("stadtwerke") || lower.contains("strom") || lower.contains("rundfunk") || lower.contains("netflix") || lower.contains("spotify") -> "Fixkosten"
            lower.contains("spar") || lower.contains("etf") || lower.contains("tagesgeld") -> "Sparen"
            else -> null
        }
        return if (targetName != null) {
            categories.firstOrNull { it.name.equals(targetName, ignoreCase = true) }
        } else {
            null
        }
    }

