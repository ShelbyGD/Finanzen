package de.smartfinance.app.data.local

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

object CategoryType {
    const val FIXED_EXPENSE = "FIXED_EXPENSE"
    const val VARIABLE_EXPENSE = "VARIABLE_EXPENSE"
    const val SAVINGS = "SAVINGS"
    const val INCOME = "INCOME"
}

object TransactionType {
    const val EXPENSE = "EXPENSE"
    const val INCOME = "INCOME"
    const val SAVINGS = "SAVINGS"
}

object BillingInterval {
    const val ONE_TIME = "ONE_TIME"
    const val MONTHLY = "MONTHLY"
    const val QUARTERLY = "QUARTERLY"
    const val YEARLY = "YEARLY"
}

/**
 * Dynamische Kategorien-Tabs, Fixkosten-Verträge, Fälligkeitstage (1..31),
 * 1/12-Glättung und Vertragsende-Wecker.
 */
@Entity(tableName = "category_tabs")
data class CategoryTabEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0L,
    val name: String,
    val iconKey: String,
    val colorHex: Long,
    val categoryType: String = CategoryType.VARIABLE_EXPENSE,
    val monthlyBudgetLimit: Double? = null,
    val dueDayOfMonth: Int? = null,
    val defaultAmount: Double? = null,
    val billingInterval: String = BillingInterval.ONE_TIME,
    val smoothOver12Months: Boolean = false,
    val contractEndDateEpochDay: Long? = null,
    val isSystemDefault: Boolean = false,
    val sortOrder: Int = 0
)

/**
 * Einzelbuchungen, Fixkosten-Abbuchungen, Einnahmen, Sparraten und geglättete Jahreskosten.
 */
@Entity(
    tableName = "transactions",
    indices = [
        Index(value = ["dateEpochDay"]),
        Index(value = ["categoryId"]),
        Index(value = ["autoGeneratedKey"], unique = true)
    ]
)
data class TransactionEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0L,
    val title: String,
    val amount: Double,
    val transactionType: String = TransactionType.EXPENSE,
    val categoryId: Long,
    val categoryName: String,
    val dateEpochDay: Long,
    val dueDayOfMonth: Int = 1,
    val isFixedRecurring: Boolean = false,
    val billingInterval: String = BillingInterval.ONE_TIME,
    val smoothOver12Months: Boolean = false,
    val note: String = "",
    val autoGeneratedKey: String? = null
) {
    val isIncome: Boolean
        get() = transactionType == TransactionType.INCOME

    val customIconKey: String?
        get() = Regex("\\[icon:([a-zA-Z0-9_-]+)\\]").find(note)?.groupValues?.get(1)

    fun resolveIconKey(categoryIconKey: String? = null): String {
        return customIconKey ?: categoryIconKey ?: when (transactionType) {
            TransactionType.INCOME -> "income"
            TransactionType.SAVINGS -> "savings"
            else -> "cart"
        }
    }

    fun withCustomIcon(iconKey: String?): TransactionEntity {
        val cleanNote = note.replace(Regex("\\[icon:([a-zA-Z0-9_-]+)\\]\\s*"), "").trim()
        val updatedNote = if (!iconKey.isNullOrBlank()) {
            if (cleanNote.isEmpty()) "[icon:$iconKey]" else "[icon:$iconKey] $cleanNote"
        } else {
            cleanNote
        }
        return this.copy(note = updatedNote)
    }
}

